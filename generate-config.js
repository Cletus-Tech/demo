// Optional helper: writes app/js/config.js from .env or from environment variables
// (useful for Netlify/Vercel/Cloudflare build settings). Usage:  node scripts/generate-config.js
const fs = require('fs'), path = require('path');
const root = path.join(__dirname, '..');
const env = { ...process.env };
const envFile = path.join(root, '.env');
if (fs.existsSync(envFile)) {
  for (const line of fs.readFileSync(envFile, 'utf8').split(/\r?\n/)) {
    const m = line.match(/^\s*([A-Z_]+)\s*=\s*(.*?)\s*$/);
    if (m && !line.trim().startsWith('#') && !(m[1] in process.env)) env[m[1]] = m[2].replace(/^["']|["']$/g, '');
  }
}
const url = env.SUPABASE_URL || '', key = env.SUPABASE_ANON_KEY || '';
function role(k) { try { return JSON.parse(Buffer.from(k.split('.')[1], 'base64url').toString()).role; } catch { return null; } }
if (!url || !key || /YOUR-/.test(url + key)) { console.error('Set SUPABASE_URL and SUPABASE_ANON_KEY in .env first.'); process.exit(1); }
if (/^sb_secret_/.test(key) || role(key) === 'service_role') { console.error('REFUSED: that is a secret key. Use the anon/publishable key.'); process.exit(1); }
const out = `/* Generated by scripts/generate-config.js. Public values only. */\nwindow.APP_CONFIG = {\n  SUPABASE_URL: ${JSON.stringify(url)},\n  SUPABASE_ANON_KEY: ${JSON.stringify(key)}\n};\n`;
fs.writeFileSync(path.join(root, 'app', 'js', 'config.js'), out);
console.log('Wrote app/js/config.js');
