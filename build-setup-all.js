// Concatenates supabase/migrations/*.sql (in order) into supabase/setup_all.sql
// so a beginner can paste ONE file into the Supabase SQL Editor.
const fs = require('fs'), path = require('path');
const dir = path.join(__dirname, '..', 'supabase', 'migrations');
const files = fs.readdirSync(dir).filter(f => /^\d{4}_.*\.sql$/.test(f)).sort();
let out = '-- AUTO-GENERATED by scripts/build-setup-all.js. Do not edit; edit the migrations instead.\n' +
          '-- Paste this whole file into Supabase > SQL Editor > New query, then press Run. Run it ONCE.\n\n';
for (const f of files) out += `\n-- ############ ${f} ############\n` + fs.readFileSync(path.join(dir, f), 'utf8') + '\n';
fs.writeFileSync(path.join(__dirname, '..', 'supabase', 'setup_all.sql'), out);
console.log('Wrote supabase/setup_all.sql from', files.length, 'migrations');
